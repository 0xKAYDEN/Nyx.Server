function AprilRewardItemAction_OpenRewardBag(nItemId)
	if Item_ChkItem(nItemId) then

		local nSpace = RewardTemplate_GetRewardSpace(tAprilRewardItemAction_RewandItem[nItemId][1])-RewardTemplate_GetDelSpace(tAprilRewardItemAction_RewandItem[nItemId][1])
		if not(User_CheckLeftSpace(nSpace)) then
		--提示
		Sys_MsgBox(string.format(tAprilRewardItemAction_Text["MsgSpace"],nSpace))
		return
		end
		RewardTemplate_UseItemAndMsg(tAprilRewardItemAction_RewandItem[nItemId][1])
	end
end

