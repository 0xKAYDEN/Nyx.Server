	if not User_CheckLeftSpace(nMayRe_Pack_Space) then
		User_TalkChannel2005(tMayRe_Pack_Text["NoSpace"],nMayRe_Pack_UserId)
		return
	end
	
	-- 给奖励
	RewardTemplate_UseItemAndMsg(tMayRe_Pack_RewardItem[nMayRe_Pack_ItemId][nMayRe_Pack_Index])
end

