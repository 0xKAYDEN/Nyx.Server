-- 金币礼包开启逻辑
function EnOctoberAction2_RewardPrice(nItemId)
	local nAddPrice = 	tEnOctoberAction2_Pack[nItemId]["RewardMoney"]["Value"]
	if not User_CanPutMoney2Bag(nAddPrice) then 
		Sys_MsgBox(tEnOctoberAction2_Text["Sys_MsgBox"]["NoPrice"])
		return
	end 
	RewardTemplate_UseItemAndMsg(tEnOctoberAction2_Pack[nItemId])
end 

-- 光环礼包
function EnOctoberAction2_RewardGHPack(nItemId)
	if not Item_ChkMulItem(nItemId,nItemId,1) then 
		return
	end 
	if Item_DelMulItem(nItemId,nItemId,1) then 
		-- local nUserId = Get_UserId()
		User_AddRoleStatus(266,200,2592000,0,0,2592000,1,1,0)
		
		local tTextLog = string.format(tEnOctoberAction2_Log["DeleteLog"],nItemId,1)
		Sys_SaveActionFestivalLog(tTextLog)  --删除log
		RewardTemplate_UseItemAndMsg(tEnOctoberAction2_Pack[nItemId])
	end 
end 

--随机奖励礼包逻辑
function EnOctoberAction2_RandomPack(nItemId)
	-- local nSpace = 2
	local nSpace = RewardTemplate_GetRandomSpace(tEnOctoberAction2_Pack,nItemId)
	if not User_CheckLeftSpace(nSpace) then  --背包空间
		User_TalkChannel2005(tEnOctoberAction2_Text["Sys_MsgBox"]["NoSpace"])
		return
	end
	-- RewardTemplate_NewRandom(tAugustActionUp_Pack,nItemId)
	RewardTemplate_RandomReward(tEnOctoberAction2_Pack,nItemId)
end

--可选包逻辑
function EnOctoberAction2_ChoicePack(nItemId,nChoNum)
	if not Item_ChkMulItem(nItemId,nItemId,1) then
		return
	end 
	local nSpace = RewardTemplate_GetRewardSpace(tEnOctoberAction2_Pack[nItemId][nChoNum])
	if not User_CheckLeftSpace(nSpace) then
		User_TalkChannel2005(string.format(tEnOctoberAction2_Text["Sys_MsgBox"]["NoSpace"],nSpace))
		return
	end
	RewardTemplate_UseItemAndMsg(tEnOctoberAction2_Pack[nItemId][nChoNum])
end


