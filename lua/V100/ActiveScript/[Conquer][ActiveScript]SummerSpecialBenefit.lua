function SummerSpecialBenefit_TimeChoiceReward_openPack(nItemId,nNum)
	if not Item_ChkItem(nItemId) then 
		return
	end
	local nItemNum = Get_CountItemType(nItemId,0)
	if CommonFunc_GetAfterActivityTime(tActivityTime["SummerSpecialBenefit"]["DeleteTime"]) then 
		Item_DelAllItemByType(nItemId)
		User_TalkChannel2005(tSummerSpecialBenefit_Text["AfterTime"])
		Sys_SaveActionFestivalLog(string.format("0,0,%d,%d,12001100,2,0,0",nItemId,nItemNum))
		return
	end
	LinkItemGossipFunc_New(nItemId,"1-1")
end

--天石商店
function SummerSpecialBenefit_OpenShop(nNpcId)
	if Sys_ChkFullTime(tActivityTime["SummerSpecialBenefit"]["BeforeTime"]) then 
	LinkNpcGossipFunc_New(nNpcId,"1-1")
		return
	end
	if CommonFunc_GetAfterActivityTime(tActivityTime["SummerSpecialBenefit"]["ActivityTime"]) then 
	LinkNpcGossipFunc_New(nNpcId,"1-2")
		return
	end
	User_OpenDialog(0,nNpcId)
end


