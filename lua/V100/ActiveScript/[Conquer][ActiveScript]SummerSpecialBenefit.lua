--限时随机奖励礼包开启通用
function SummerSpecialBenefit_TimeRandomReward_openPack(nItemId)
	local nItemNum = Get_CountItemType(nItemId,0)
	if not Item_ChkItem(nItemId) then 
		return
	end
	if CommonFunc_GetAfterActivityTime(tActivityTime["SummerSpecialBenefit"]["DeleteTime"]) then 
		Item_DelAllItemByType(nItemId)
		User_TalkChannel2005(tSummerSpecialBenefit_Text["AfterTime"])
		Sys_SaveActionFestivalLog(string.format("0,0,%d,%d,12001100,2,0,0",nItemId,nItemNum))
		return
	end 
	local nEMoney = tSummerSpecialBenefit_Pack[nItemId][8]["RewardEMoney"]["Value"]
	local nUserEMoney = Get_UserEMoney()
	if nEMoney + nUserEMoney > G_User_MaxEmoney then    ---检查天石（赠）是否达到上限
		User_TalkChannel2005(tSummerSpecialBenefit_Text["EMoneyMono"])
		return
	end
	local space = RewardTemplate_GetRandomSpace(tSummerSpecialBenefit_Pack,nItemId)
	if not User_CheckLeftSpace(space) then
		User_TalkChannel2005(string.format(tSummerSpecialBenefit_Text["TextNoSpace"],space))
		return
	end
	if Item_ChkItem(nItemId) and Item_DelItem(nItemId) then
		RewardTemplate_NewRandom(tSummerSpecialBenefit_Pack,nItemId)
	end
end
