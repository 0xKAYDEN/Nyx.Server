--赠点礼包逻辑
function EnOctoberAction1_RewardMono(nItemId)
	local nRewardEMoneyM = tEnOctoberAction1_Pack[nItemId]["RewardEMoneyMono"]["Value"]
	if Get_UserMonoEMoney() + nRewardEMoneyM > G_User_MaxEmoneyMono then  --赠点上限
		User_TalkChannel2005(tEnOctoberAction1_Text["Sys_MsgBox"]["NoMonomoney"])
		return
	end 
	RewardTemplate_UseItemAndMsg(tEnOctoberAction1_Pack[nItemId])
end 

--天石礼包逻辑
function EnOctoberAction1_RewardEmoney(nItemId)
	local nRewardEMoney = tEnOctoberAction1_Pack[nItemId]["RewardEMoney"]["Value"]
	if Get_UserEMoney() + nRewardEMoney > G_User_MaxEmoney then  --天石上限
		User_TalkChannel2005(tEnOctoberAction1_Text["Sys_MsgBox"]["NotEMoney"])
		return
	end 
	RewardTemplate_UseItemAndMsg(tEnOctoberAction1_Pack[nItemId])
end 
--包含天石的可选包
function EnOctoberAction1_ChoiceEmoneyPack(nItemId,nChoNum)
	if not Item_ChkMulItem(nItemId,nItemId,1) then
		return
	end 
	if nChoNum == 1 then 
		local nSpace = RewardTemplate_GetRewardSpace(tEnOctoberAction1_Pack[nItemId][nChoNum])
		if not User_CheckLeftSpace(nSpace) then
			User_TalkChannel2005(string.format(tEnOctoberAction1_Text["Sys_MsgBox"]["NoSpace"],nSpace))
			return
		end
		RewardTemplate_UseItemAndMsg(tEnOctoberAction1_Pack[nItemId][nChoNum])
	elseif nChoNum == 2 then 
		local nRewardEMoney = tEnOctoberAction1_Pack[nItemId][nChoNum]["RewardEMoney"]["Value"]
		if Get_UserEMoney() + nRewardEMoney > G_User_MaxEmoney then  --天石上限
			User_TalkChannel2005(tEnOctoberAction1_Text["Sys_MsgBox"]["NotEMoney"])
			return
		end 
		RewardTemplate_UseItemAndMsg(tEnOctoberAction1_Pack[nItemId][nChoNum])
	end 
end 


--可选包逻辑
function EnOctoberAction1_ChoicePack(nItemId,nChoNum)
	if not Item_ChkMulItem(nItemId,nItemId,1) then
		return
	end 
	local nSpace = RewardTemplate_GetRewardSpace(tEnOctoberAction1_Pack[nItemId][nChoNum])
	if not User_CheckLeftSpace(nSpace) then
		User_TalkChannel2005(string.format(tEnOctoberAction1_Text["Sys_MsgBox"]["NoSpace"],nSpace))
		return
	end
	RewardTemplate_UseItemAndMsg(tEnOctoberAction1_Pack[nItemId][nChoNum])
end

