-----------------------------逻辑 
--固定奖励礼包开启
function JulyTerritorialHegemony_openPack(nItemId)
	if not Item_ChkItem(nItemId) then 
		return
	end
	local space = RewardTemplate_GetRewardSpace(tJulyTerritorialHegemony_Pack[nItemId])
	if not User_CheckLeftSpace(space) then
		User_TalkChannel2005(string.format(tJulyTerritorialHegemony_Text["TextNoSpace"],space))
		return
	end
	if Item_ChkItem(nItemId) and Item_DelItem(nItemId) then
		RewardTemplate_Reward(tJulyTerritorialHegemony_Pack[nItemId])
	end
end
--天石礼包开启
function JulyTerritorialHegemony_openEMoneyMonoPack(nItemId)
	if not Item_ChkItem(nItemId) then 
		return
	end
	local nEMoneyMono = tJulyTerritorialHegemony_Pack[nItemId]["RewardEMoneyMono"]["Value"]
	local nUserEMoneyMono = Get_UserMonoEMoney()
	if nEMoneyMono + nUserEMoneyMono > G_User_MaxEmoneyMono then    ---检查天石（赠）是否达到上限
		User_TalkChannel2005(tJulyTerritorialHegemony_Text["EMoneyMono"])
		return
	end
	local space = RewardTemplate_GetRewardSpace(tJulyTerritorialHegemony_Pack[nItemId])
	if not User_CheckLeftSpace(space) then
		User_TalkChannel2005(string.format(tJulyTerritorialHegemony_Text["TextNoSpace"],space))
		return
	end
	if Item_ChkItem(nItemId) and Item_DelItem(nItemId) then
		RewardTemplate_Reward(tJulyTerritorialHegemony_Pack[nItemId])
	end
end

