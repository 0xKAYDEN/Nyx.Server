function ProducesWealthAction_Open(nItemId)
	local nUserId = Get_UserId()
	
	-- 判断物品是否存在
	if not Item_ChkItem(nItemId) then
		return
	end
	
	-- 奖励所需要的背包空间
	local nNeedSpace = RewardTemplate_GetRandomSpace(tProducesWealthAction_Reward[nItemId], 1)
	-- 获取删除物品所需的背包空间
	local nDelSpace = RewardTemplate_GetDelSpace(tProducesWealthAction_Reward[nItemId], nUserId)
	local nSpace = nNeedSpace - nDelSpace
	
	-- 判断背包空间是否足够
	if nSpace > 0 and (not User_CheckLeftSpace(nSpace,nUserId)) then
		Sys_MsgBox(tProducesWealthAction_Text["BagFull"])
		return
	end
	
	-- 删物品
	if not Item_DelItem(nItemId) then
		return
	end
	
	RewardTemplate_NewRandom(tProducesWealthAction_Reward[nItemId], 1)
end

